"""Временный каталог pytest, который нельзя испортить.

История: `%TEMP%\\pytest-of-*`, `.pytest-tmp`, `.pytest-tmp-b`, `.pytest-run` —
четыре каталога подряд стали недоступны самому же владельцу проекта, и `takeown`
без прав администратора их не берёт. Переезд на новое имя лечил симптом на один
раз, поэтому причину пришлось найти.

Причина не в порче ACL и не в Windows, а в связке двух вещей:

1. С Python 3.13 `os.mkdir(mode=0o700)` на Windows наконец **применяет** режим:
   каталог получает защищённый (`D:P`) дескриптор `SYSTEM / Администраторы /
   ПРАВА ВЛАДЕЛЬЦА` — наследование от родителя отключено, а доступ есть только
   у того, кто каталог создал.
2. `--basetemp` заставляет pytest создавать этим самым `mkdir(mode=0o700)`
   каталог с **постоянным именем** (`getbasetemp` в `_pytest/tmpdir.py`).

Пока каждый прогон идёт под одним и тем же пользователем, всё работает. Стоит
одному прогону случиться под другим токеном (терминал «от имени администратора»
— у такого токена владельцем создаваемых объектов становится группа
«Администраторы»), и постоянное имя оказывается занято каталогом, к которому
обычный процесс не имеет доступа вовсе: ни удалить, ни прочитать права. Дальше
каждый следующий прогон падает на этом же месте.

Лечение — не новое имя, а правило: **каждый каталог с постоянным именем создаём
сами обычным `mkdir`**. Такой каталог наследует права от репозитория, и владелец
проекта сохраняет к нему доступ, кем бы он ни был создан. Каталогам с режимом
`0o700` остаются только нумерованные листья `pytest-N`, а их pytest никогда не
переиспользует: номер растёт, недоступный лист молча пропускается при уборке
(`ensure_deletable`, pytest #7491).

Поэтому `--basetemp` убран из `addopts`, а вместо него задаётся
`PYTEST_DEBUG_TEMPROOT` — pytest возвращается к своей штатной схеме
с нумерацией и уборкой, но внутри репозитория.
"""

import getpass
import os
from pathlib import Path

_TEMPROOT = Path(__file__).parent / ".pytest-temp"


def _prepare_temproot() -> Path:
    """Создать каталоги с постоянными именами до того, как до них дойдёт pytest."""
    try:
        user = getpass.getuser()
    except (OSError, KeyError):
        user = "unknown"

    _TEMPROOT.mkdir(exist_ok=True)
    # Точное имя из _pytest.tmpdir.getbasetemp: попадём — pytest созданный нами
    # каталог примет как есть (`exist_ok=True` режим не применяет), промахнёмся —
    # он создаст свой, и мы вернёмся к прежнему поведению, а не сломаемся.
    (_TEMPROOT / f"pytest-of-{user}").mkdir(exist_ok=True)
    return _TEMPROOT


def pytest_configure(config: object) -> None:
    """Увести временные файлы тестов в репозиторий, не отдавая имена pytest."""
    os.environ.setdefault("PYTEST_DEBUG_TEMPROOT", str(_prepare_temproot()))
